// Function to safely trigger Google Website Translator
const triggerGoogleTranslate = (langCode) => {
  try {
    if (langCode === 'en') {
      const domains = ['', window.location.hostname, '.' + window.location.hostname];
      const paths = ['/', window.location.pathname];
      for (const d of domains) {
        for (const p of paths) {
          document.cookie = `googtrans=; expires=Thu, 01 Jan 1970 00:00:00 UTC; path=${p};${d ? ` domain=${d};` : ''}`;
        }
      }
      const teCombo = document.querySelector('.goog-te-combo');
      if (teCombo && teCombo.value && teCombo.value !== 'en') {
        teCombo.value = 'en';
        teCombo.dispatchEvent(new Event('change'));
      }
    } else {
      const targetLang = langCode === 'hinglish' ? 'hi' : langCode;
      const cookieValue = `/en/${targetLang}`;
      const domains = ['', window.location.hostname, '.' + window.location.hostname];
      for (const d of domains) {
        document.cookie = `googtrans=${cookieValue}; path=/;${d ? ` domain=${d};` : ''}`;
      }
      const teCombo = document.querySelector('.goog-te-combo');
      if (teCombo) {
        teCombo.value = targetLang;
        teCombo.dispatchEvent(new Event('change'));
      }
    }
  } catch (e) {
    console.debug('Google translate sync event:', e);
  }
};

export const LanguageProvider = ({ children }) => {
  const [language, setLanguageState] = useState(() => {
    // Reset to English by default as requested by user
    const initialized = localStorage.getItem('gov_lang_default_v3');
    if (!initialized) {
      localStorage.setItem('gov_lang_default_v3', 'true');
      localStorage.setItem('gov_language', 'en');
      return 'en';
    }
    return localStorage.getItem('gov_language') || 'en';
  });

  const setLanguage = (langCode) => {
    localStorage.setItem('gov_language', langCode);
    setLanguageState(langCode);
    triggerGoogleTranslate(langCode);
  };

  useEffect(() => {
    // Synchronize on initial render
    triggerGoogleTranslate(language);
  }, [language]);

  /**
   * Smart Translation Function:
   * 1. Check exact key in active language
   * 2. Check normalized string phrase in active language
   * 3. Fallback to English dictionary
   * 4. Fallback to defaultText or original text
   */
  const t = (keyOrText, defaultText) => {
    if (!keyOrText) return '';
    const key = String(keyOrText).trim();

    // 1. Direct key match in chosen language
    if (TRANSLATIONS[language] && TRANSLATIONS[language][key] !== undefined) {
      return TRANSLATIONS[language][key];
    }

    // 2. Direct key match in English
    if (TRANSLATIONS.en && TRANSLATIONS.en[key] !== undefined && language === 'en') {
      return TRANSLATIONS.en[key];
    }

    // 3. Reverse lookup if an English value was passed as text
    if (TRANSLATIONS[language]) {
      // Check if this text corresponds to any known English key
      for (const [k, v] of Object.entries(TRANSLATIONS.en)) {
        if (v === key && TRANSLATIONS[language][k] !== undefined) {
          return TRANSLATIONS[language][k];
        }
      }
    }

    // 4. Default fallback
    if (defaultText !== undefined) {
      return defaultText;
    }

    if (TRANSLATIONS.en && TRANSLATIONS.en[key] !== undefined) {
      return TRANSLATIONS.en[key];
    }

    return keyOrText;
  };

  return (
    <LanguageContext.Provider value={{ language, setLanguage, t, supportedLanguages: SUPPORTED_LANGUAGES }}>
      {children}
    </LanguageContext.Provider>
  );
};

export const useLanguage = () => useContext(LanguageContext);
